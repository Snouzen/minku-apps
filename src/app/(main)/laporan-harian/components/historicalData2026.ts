/**
 * Smart helper to extract actual inventory quantity in Kg (or Pcs for packaging)
 * Business Rule:
 * - KEMASAN: Returns Remaining Qty as Pcs (no pack multiplier).
 * - GKG, GKP, PRODUK SAMPINGAN, etc.: Returns Remaining Qty as Kg (no pack multiplier).
 * - BERAS BAHAN BAKU & BERAS JADI:
 *   1. If explicit 'Qty (Kg)' column exists with valid value > 0, use it.
 *   2. If 'Pack' column exists with valid value > 0, use Remaining Qty * Pack.
 *   3. Dynamic Fallback: Parse pack size from product name (e.g. "[B0020046A] ... 5 KG" -> 5) and multiply Remaining Qty * packSize.
 *      If no pack size pattern is found (e.g. curah/bulk), packSize defaults to 1.
 */
export function getInventoryRealQty(
  row: Record<string, any>,
  columns?: string[],
  isPackaging = false
): number {
  if (!row) return 0;
  const cols = columns || [];

  const catCol = cols.find(c => {
    const s = c.toLowerCase();
    return s.includes('category') || s.includes('kategori') || s.includes('komoditi');
  }) || 'Product Category';

  const prodCol = cols.find(c => {
    const s = c.toLowerCase();
    return s === 'product' || s.includes('produk') || s.includes('item') || s.includes('barang') || s.includes('deskripsi') || s.includes('description') || s.includes('nama');
  }) || 'Product';

  const remCol = cols.find(c => {
    const s = c.toLowerCase();
    return s.includes('remaining') || s.includes('qty') || s.includes('kuantum') || s.includes('stok') || s.includes('stock') || s.includes('saldo') || s.includes('jumlah');
  }) || 'Remaining Qty';

  const cat = (row[catCol] || '').toString().toUpperCase().trim();
  const prod = (row[prodCol] || '').toString().toUpperCase().trim();

  let rawRem = row[remCol];
  if (typeof rawRem === 'string') rawRem = parseFloat(rawRem.replace(/,/g, ''));
  const baseQty = typeof rawRem === 'number' && !isNaN(rawRem) ? rawRem : 0;

  // 1. Packaging check (returns count in Pcs)
  if (isPackaging || cat.includes('KEMASAN') || prod.startsWith('[D') || prod.includes('KARPLAS')) {
    return baseQty;
  }

  // 2. Check if product is Rice (Beras Bahan Baku / Beras Jadi)
  const isRice = (
    cat === 'BERAS BAHAN BAKU' ||
    cat === 'BERAS JADI' ||
    (cat.includes('BERAS') && !cat.includes('WIP') && !cat.includes('MAKLON') && !cat.includes('SAMPINGAN')) ||
    prod.startsWith('[A004') ||
    prod.startsWith('[B00')
  );

  // If NOT rice (e.g. GKG, GKP, Produk Sampingan, Spare parts, etc.), return Remaining Qty directly (kg)
  if (!isRice) {
    return baseQty;
  }

  // 3. For Rice: Check explicit Kg column first if provided
  const explicitKgCol = cols.find(c => {
    const s = c.toLowerCase();
    return s.includes('(kg)') || s.includes('qty kg') || s.includes('kuantum kg');
  });
  if (explicitKgCol && row[explicitKgCol] !== undefined && row[explicitKgCol] !== null && row[explicitKgCol] !== '') {
    let val = row[explicitKgCol];
    if (typeof val === 'string') val = parseFloat(val.replace(/,/g, ''));
    if (typeof val === 'number' && !isNaN(val) && val > 0) {
      return val;
    }
  }

  // 4. Check explicit Pack column
  const packCol = cols.find(c => {
    const s = c.toLowerCase();
    return s === 'pack' || s.includes('kemasan pack');
  });
  let packSize = 1;
  if (packCol && row[packCol] !== undefined && row[packCol] !== null && row[packCol] !== '') {
    let p = row[packCol];
    if (typeof p === 'string') p = parseFloat(p.replace(/,/g, ''));
    if (typeof p === 'number' && !isNaN(p) && p > 0) {
      packSize = p;
    }
  } else {
    // 5. Extract pack size from product name (e.g. '5 KG', '10 KG', '25 KG', '50 KG', '3 KG')
    const match = prod.match(/(\d+(?:\.\d+)?)\s*(?:KG|kg|Kg)/);
    if (match) {
      packSize = parseFloat(match[1]) || 1;
    }
  }

  return baseQty * packSize;
}



